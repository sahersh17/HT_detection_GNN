"""Fetch only pinned Verilog compilation files declared in shuttle manifests."""
import ast
import hashlib
import re
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from planning import ROOT,RUN,read,report

def tokens(text):
    return expr.findall(re.sub(r"/\*.*?\*/|//[^\n]*","",text,flags=re.S))

tree=ast.parse((ROOT/"experiments/tier3_admission_v1/admission.py").read_text())
expr=re.compile(next(n.value.args[0].value for n in tree.body if isinstance(n,ast.Assign) and getattr(n.targets[0],"id","")=="TOKENS"))

def fetch(item):
    owner_repo=item["repo"].removeprefix("https://github.com/").rstrip("/")
    commit=item["commit"];host=item["host"]
    names=item["files"]
    if not (re.fullmatch(r"[\w.-]+/[\w.-]+",owner_repo) and re.fullmatch("[0-9a-f]{40}",commit)
            and re.fullmatch(r"\w+",host) and all(re.fullmatch(r"[\w.-]+\.v",n) for n in names)):return
    folder=RUN/"originals"/commit
    folder.mkdir(parents=True,exist_ok=True)
    files=[];sha={}; types=set()
    try:
        for n in names:
            p=folder/n
            if not p.exists():
                url=f"https://raw.githubusercontent.com/{owner_repo}/{commit}/src/{n}"
                with urllib.request.urlopen(url,timeout=15) as response:data=response.read(4000001)
                if len(data)>4000000:raise ValueError("oversize")
                p.write_bytes(data)
            data=p.read_bytes()
            text=data.decode("utf-8",errors="replace")
            if re.search(r'\bsky130_fd_|Generated by Yosys|Generated by Amaranth|\$readmem|^`include',text,re.I|re.M):
                raise ValueError("nonportable dependencies or generated netlist")
            files+=tokens(text);sha[n]=hashlib.sha256(data).hexdigest()
            types.update(re.findall(r'^\s*module\s+(\w+)',text,re.M))
        if host not in types:raise ValueError("top not declared")
        return dict(**item,tokens=len(files),sha256=sha)
    except Exception as e:return dict(**item,error=str(e)[:180])

if __name__=="__main__":
    seen=set();unique=[]
    for it in read(RUN/"inventory.json"):
        if it["repo"].lower() not in seen:
            unique.append(it);seen.add(it["repo"].lower())
    with ThreadPoolExecutor(max_workers=10) as pool:
        out=[x for x in pool.map(fetch,unique) if x]
    report(RUN/"candidates.json",out)
    print(len(out),sum(1343<=x.get("tokens",0)<=20907 for x in out),"in range")
